//! AGENTS.md / MEMORY.md generation and destination-directory mapping.

use crate::app::App;
use crate::manifest::write_file_with_agentic_marker;
use crate::ui;
use std::path::{Path, PathBuf};

/// Destination directory for a bucket per agent OS ("-" means skip).
pub fn get_dest_dir(agent_os: &str, bucket: &str) -> String {
    let mapping: Option<[&str; 3]> = match agent_os {
        "opencode" => Some([".opencode/rules", ".opencode/skills", ".opencode/commands"]),
        "cursor" => Some([".cursor/rules", ".cursor/skills", "-"]),
        // Codex discovers skills only in `.agents/skills`; rules stay in `.agent/rules`.
        "codex" => Some([".agent/rules", ".agents/skills", ".agent/workflows"]),
        // Workflows stay in .agent/workflows; .claude/commands holds thin wrappers.
        "claude" => Some([".claude/rules", ".claude/skills", "-"]),
        "kilocode" | "antigravity" => {
            Some([".kilocode/rules", ".kilocode/skills", ".kilocode/workflows"])
        }
        _ => None,
    };
    match mapping {
        Some(parts) => match bucket {
            "rules" => parts[0].to_string(),
            "skills" => parts[1].to_string(),
            "workflows" => parts[2].to_string(),
            _ => format!(".agent/{bucket}"),
        },
        None => format!(".agent/{bucket}"),
    }
}

fn build_header(app: &App) -> String {
    let rules_dir = get_dest_dir(&app.selected_agent_os[0], "rules");
    let company = if crate::company::configured(app) {
        let mut text = format!("{}\n", crate::company::AGENTS_LINE);
        for line in &app.company_agents_lines {
            text.push_str(line);
            text.push('\n');
        }
        text.push('\n');
        text
    } else {
        String::new()
    };
    format!(
        "# Agentic Project Guidelines\n\nGenerated by {}.\n\n## Installation Context\n- Agent OS targets: {}\n- Primary agent rules directory: {}\n- Areas: {}\n- Specializations: {}\n\n{company}---\n\n",
        crate::APP_NAME,
        app.selected_agent_os.join(" "),
        rules_dir,
        app.selected_areas.join(" "),
        app.selected_specs.join(" "),
    )
}

fn append_root_agents_template(app: &App, out: &mut String) {
    out.push_str("## Shared guidance\n\n");
    match app.kb.read_file("AGENTS.md") {
        Some(content) => out.push_str(&content),
        None => out.push_str("No root AGENTS.md template found.\n"),
    }
    out.push_str("\n---\n\n");
}

fn append_specialization_template(app: &App, out: &mut String, spec_key: &str) {
    let (area, spec) = spec_key.split_once('.').unwrap_or((spec_key, ""));
    out.push_str(&format!("## {area}/{spec}\n\n"));
    match app.kb.read_file(&format!("areas/{area}/{spec}/AGENTS.md")) {
        Some(content) => out.push_str(&content),
        None => out.push_str(&format!(
            "No specialization AGENTS.md template found for {spec_key}.\n"
        )),
    }
    out.push_str("\n---\n\n");
}

/// `--agents-md` values: `generate` writes root `AGENTS.md`; `keep` leaves it to the project.
pub const MODE_GENERATE: &str = "generate";
pub const MODE_KEEP: &str = "keep";
/// The canonical generated guidance in `keep` mode.
pub const KEEP_OUTPUT: &str = ".agent/AGENTS.md";
/// Codex reads `AGENTS.override.md` instead of `AGENTS.md` in the same directory.
pub const CODEX_OVERRIDE: &str = "AGENTS.override.md";
const SOURCE: &str = "generated:AGENTS.md";
const OPENCODE_OUTPUT: &str = ".opencode/AGENTS.md";
/// The OpenCode config that agentic manages; OpenCode loads it as a project config source.
const OPENCODE_CONFIG: &str = ".opencode/opencode.json";
/// `config_owned_keys` entry for the one `instructions` item that agentic adds (JSON pointer escaping).
pub const OPENCODE_INSTRUCTION_KEY: &str = "/instructions/.agent~1AGENTS.md";

pub fn parse_mode(value: &str) -> crate::Result<String> {
    match value.trim() {
        v @ (MODE_GENERATE | MODE_KEEP) => Ok(v.to_string()),
        other => Err(format!("--agents-md: expected generate or keep, got '{other}'").into()),
    }
}

/// True when root `AGENTS.md` belongs to the project (`--agents-md keep`).
pub fn keep_mode(app: &App) -> bool {
    app.agents_md_mode.as_deref() == Some(MODE_KEEP)
}

/// Take the saved `settings.agents_md` when the CLI did not set a mode.
pub fn load_saved_mode(app: &mut App, settings: &serde_json::Value) {
    if app.agents_md_mode.is_none() {
        if let Some(mode) = settings["agents_md"]
            .as_str()
            .filter(|m| *m == MODE_GENERATE || *m == MODE_KEEP)
        {
            app.agents_md_mode = Some(mode.to_string());
        }
    }
}

/// `install` paths (the TUI among them) that did not replay the manifest still keep its mode.
pub fn resolve_mode(app: &mut App) {
    if app.agents_md_mode.is_some() {
        return;
    }
    let settings = std::fs::read_to_string(app.project_manifest_path())
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .map(|d| d["settings"].clone())
        .unwrap_or(serde_json::Value::Null);
    load_saved_mode(app, &settings);
}

fn generated_content(app: &App) -> String {
    let mut content = build_header(app);
    append_root_agents_template(app, &mut content);
    for spec_key in app.selected_specs.clone() {
        append_specialization_template(app, &mut content, &spec_key);
    }
    content
}

/// The project's root `AGENTS.md` text that `keep` mode puts above the generated guidance.
fn project_agents_md(app: &mut App, project_dir: &Path) -> Option<String> {
    let path = project_dir.join("AGENTS.md");
    let Ok(text) = std::fs::read_to_string(&path) else {
        ui::warn(
            app,
            &format!(
                "--agents-md keep: no AGENTS.md at the project root; agentic does not create it. \
                 The generated guidance is in {KEEP_OUTPUT} only"
            ),
        );
        return None;
    };
    if crate::project_inventory::recognized(&text) {
        ui::warn(
            app,
            "--agents-md keep: AGENTS.md still holds guidance that agentic generated earlier. \
             agentic no longer changes it; replace it with the short project AGENTS.md",
        );
        return None;
    }
    Some(text)
}

pub fn generate_agents_md(app: &mut App, project_dir: &Path) -> crate::Result<()> {
    let keep = keep_mode(app);
    let mut outputs: Vec<PathBuf> = Vec::new();
    // In keep mode OpenCode gets .agent/AGENTS.md through `instructions` (sync_opencode_instructions).
    if app.selected_agent_os_contains("opencode") && !keep {
        outputs.push(project_dir.join(OPENCODE_OUTPUT));
    }
    if keep {
        outputs.push(project_dir.join(KEEP_OUTPUT));
        if app.selected_agent_os_contains("codex") {
            outputs.push(project_dir.join(CODEX_OVERRIDE));
        }
    } else {
        outputs.push(project_dir.join("AGENTS.md"));
    }

    if app.dry_run {
        for out in &outputs {
            ui::log(app, &format!("DRY-RUN generate {}", out.display()));
            app.record_copied(&out.to_string_lossy());
        }
        return Ok(());
    }

    app.ensure_dir(project_dir);
    if !keep {
        // Files of an earlier `keep` install; a stale AGENTS.override.md would hide AGENTS.md from Codex.
        for rel in [KEEP_OUTPUT, CODEX_OVERRIDE] {
            remove_generated(app, project_dir, rel)?;
        }
    } else {
        remove_generated(app, project_dir, OPENCODE_OUTPUT)?;
        if !app.selected_agent_os_contains("codex") {
            remove_generated(app, project_dir, CODEX_OVERRIDE)?;
        }
    }
    let mut content = generated_content(app);
    if keep {
        if let Some(root) = project_agents_md(app, project_dir) {
            content = format!("{}\n\n---\n\n{content}", root.trim_end());
        }
    }
    for out in outputs {
        write_file_with_agentic_marker(app, &content, &out, SOURCE)?;
    }
    Ok(())
}

/// Keep mode with OpenCode: add `.agent/AGENTS.md` to `instructions` of `.opencode/opencode.json`. Other items
/// stay. Without keep mode (or OpenCode) the item that agentic added is removed again.
pub fn sync_opencode_instructions(app: &mut App, project_dir: &Path) -> crate::Result<()> {
    let dest = project_dir.join(OPENCODE_CONFIG);
    let wanted = keep_mode(app) && app.selected_agent_os_contains("opencode");
    if wanted {
        return crate::manifest::write_json_config_file(
            app,
            &dest,
            "generated:opencode-instructions",
            |data, _| {
                let list = data
                    .entry("instructions")
                    .or_insert_with(|| serde_json::json!([]));
                if !list.is_array() {
                    *list = serde_json::json!([]);
                }
                let items = list.as_array_mut().unwrap();
                if !items.iter().any(|v| v == KEEP_OUTPUT) {
                    items.push(serde_json::json!(KEEP_OUTPUT));
                }
            },
        );
    }
    if app.dry_run
        || !dest.is_file()
        || !crate::upgrade_config::owns_key(app, OPENCODE_CONFIG, OPENCODE_INSTRUCTION_KEY)
    {
        return Ok(());
    }
    crate::util::unique_append(
        app.config_released_keys
            .entry(OPENCODE_CONFIG.into())
            .or_default(),
        OPENCODE_INSTRUCTION_KEY,
    );
    crate::manifest::write_json_config_file(
        app,
        &dest,
        "generated:opencode-instructions",
        |data, _| {
            let empty = match data.get_mut("instructions").and_then(|v| v.as_array_mut()) {
                Some(items) => {
                    items.retain(|v| v != KEEP_OUTPUT);
                    items.is_empty()
                }
                None => false,
            };
            if empty {
                data.remove("instructions");
            }
        },
    )
}

/// Remove a file that this generator wrote earlier, if the user did not change it.
fn remove_generated(app: &mut App, project_dir: &Path, rel: &str) -> crate::Result<()> {
    let ours = std::fs::read_to_string(app.project_manifest_path())
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .and_then(|d| d["managed_files"].as_array().cloned())
        .into_iter()
        .flatten()
        .any(|i| i["path"] == rel && i["source"] == SOURCE);
    if ours {
        crate::legacy::remove_if_unmodified(app, project_dir, rel, "generated AGENTS.md")?;
    }
    Ok(())
}

/// Paths that a `keep` install generates and the project usually does not commit.
pub fn print_keep_hint(app: &App) {
    if !keep_mode(app) {
        return;
    }
    let claude = if crate::company::configured(app) {
        ".claude/ (except rules/company-* when the project commits company rules)"
    } else {
        ".claude/"
    };
    ui::out(app, "");
    ui::out(
        app,
        "--agents-md keep: root AGENTS.md is yours; agentic generated the rest. \
         Add the generated paths to .gitignore, for example:",
    );
    for path in [
        ".agent/* (except files the project commits, such as .agent/company or .agent/gate.json)",
        ".agents/",
        claude,
        ".codex/",
        ".opencode/",
        "AGENTS.override.md",
        ".agentic.json",
        "MEMORY.md",
        "REVIEW_PIPELINE.md",
        "CLAUDE.md",
    ] {
        ui::out(app, &format!("  {path}"));
    }
}

pub fn copy_memory_md(app: &mut App, project_dir: &Path) -> crate::Result<()> {
    let Some(src) = app.kb.read_file("MEMORY.md") else {
        ui::warn(app, "MEMORY.md not found in knowledge base; skipping");
        return Ok(());
    };
    let mut outputs: Vec<PathBuf> = Vec::new();
    if app.selected_agent_os_contains("opencode") {
        outputs.push(project_dir.join(".opencode/MEMORY.md"));
    }
    let needs_root = app.selected_agent_os.iter().any(|a| a != "opencode");
    if needs_root || !app.selected_agent_os_contains("opencode") {
        outputs.push(project_dir.join("MEMORY.md"));
    }
    for out in outputs {
        write_file_with_agentic_marker(app, &src, &out, "generated:MEMORY.md")?;
    }
    Ok(())
}

pub fn copy_review_pipeline(app: &mut App, project_dir: &Path) -> crate::Result<()> {
    let content = app
        .kb
        .read_file("REVIEW_PIPELINE.md")
        .ok_or("REVIEW_PIPELINE.md not found in knowledge base")?;
    write_file_with_agentic_marker(
        app,
        &content,
        &project_dir.join("REVIEW_PIPELINE.md"),
        "REVIEW_PIPELINE.md",
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dest_dir_mappings() {
        assert_eq!(get_dest_dir("opencode", "rules"), ".opencode/rules");
        assert_eq!(get_dest_dir("opencode", "workflows"), ".opencode/commands");
        assert_eq!(get_dest_dir("cursor", "skills"), ".cursor/skills");
        assert_eq!(get_dest_dir("cursor", "workflows"), "-");
        assert_eq!(get_dest_dir("kilocode", "workflows"), ".kilocode/workflows");
        assert_eq!(get_dest_dir("antigravity", "rules"), ".kilocode/rules");
        assert_eq!(get_dest_dir("default", "rules"), ".agent/rules");
        assert_eq!(get_dest_dir("codex", "skills"), ".agents/skills");
        assert_eq!(get_dest_dir("claude", "rules"), ".claude/rules");
        assert_eq!(get_dest_dir("claude", "skills"), ".claude/skills");
        assert_eq!(get_dest_dir("claude", "workflows"), "-");
        assert_eq!(get_dest_dir("agents", "skills"), ".agent/skills");
        assert!(!crate::INSTALL_DIRS.contains(&"prompts"));
    }

    fn test_app(project: &Path) -> App {
        let mut app = App::new().unwrap();
        app.project_dir = project.to_string_lossy().to_string();
        app.selected_agent_os = vec!["default".to_string()];
        app.selected_areas = vec!["software".to_string()];
        app.selected_specs = vec!["software.backend".to_string()];
        app
    }

    #[test]
    fn generates_agents_md_with_sections() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        generate_agents_md(&mut app, tmp.path()).unwrap();
        let content = std::fs::read_to_string(tmp.path().join("AGENTS.md")).unwrap();
        assert!(content.contains("# Agentic Project Guidelines"));
        assert!(content.contains("## Shared guidance"));
        assert!(content.contains("## software/backend"));
        assert!(content.starts_with("---\nagentic:\n"));
    }

    #[test]
    fn opencode_gets_extra_agents_md() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.selected_agent_os = vec!["opencode".to_string()];
        generate_agents_md(&mut app, tmp.path()).unwrap();
        assert!(tmp.path().join(".opencode/AGENTS.md").is_file());
        assert!(tmp.path().join("AGENTS.md").is_file());
    }

    #[test]
    fn agents_md_mode_parse_and_saved_value() {
        assert_eq!(parse_mode("keep").unwrap(), MODE_KEEP);
        assert_eq!(parse_mode(" generate ").unwrap(), MODE_GENERATE);
        assert!(parse_mode("both").is_err());
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        load_saved_mode(&mut app, &serde_json::json!({"agents_md": "bogus"}));
        assert!(!keep_mode(&app));
        load_saved_mode(&mut app, &serde_json::json!({"agents_md": "keep"}));
        assert!(keep_mode(&app));
        app.agents_md_mode = Some(MODE_GENERATE.into());
        load_saved_mode(&mut app, &serde_json::json!({"agents_md": "keep"}));
        assert!(!keep_mode(&app), "the CLI value wins");
    }

    #[test]
    fn keep_mode_prefixes_project_text_and_skips_root() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.selected_agent_os = vec!["codex".to_string()];
        app.agents_md_mode = Some(MODE_KEEP.into());
        std::fs::write(tmp.path().join("AGENTS.md"), "# Mine\n").unwrap();
        generate_agents_md(&mut app, tmp.path()).unwrap();
        assert_eq!(
            std::fs::read_to_string(tmp.path().join("AGENTS.md")).unwrap(),
            "# Mine\n"
        );
        for rel in [KEEP_OUTPUT, CODEX_OVERRIDE] {
            let text = std::fs::read_to_string(tmp.path().join(rel)).unwrap();
            assert!(text.contains("---\n# Mine\n\n---\n\n# Agentic Project Guidelines"));
        }
        assert!(!app.managed_records.iter().any(|r| r.path == "AGENTS.md"));
    }

    #[test]
    fn memory_md_placement() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.selected_agent_os = vec!["opencode".to_string()];
        copy_memory_md(&mut app, tmp.path()).unwrap();
        assert!(tmp.path().join(".opencode/MEMORY.md").is_file());
        assert!(!tmp.path().join("MEMORY.md").exists());

        let tmp2 = tempfile::tempdir().unwrap();
        let mut app2 = test_app(tmp2.path());
        app2.selected_agent_os = vec!["opencode".to_string(), "codex".to_string()];
        copy_memory_md(&mut app2, tmp2.path()).unwrap();
        assert!(tmp2.path().join(".opencode/MEMORY.md").is_file());
        assert!(tmp2.path().join("MEMORY.md").is_file());
    }

    #[test]
    fn review_protocol_install_from_embedded_and_checkout() {
        for kb in [
            crate::kb::Kb::Embedded,
            crate::kb::Kb::Checkout(PathBuf::from(env!("CARGO_MANIFEST_DIR"))),
        ] {
            let tmp = tempfile::tempdir().unwrap();
            let mut app = test_app(tmp.path());
            app.kb = kb;
            copy_review_pipeline(&mut app, tmp.path()).unwrap();
            let content = std::fs::read_to_string(tmp.path().join("REVIEW_PIPELINE.md")).unwrap();
            assert!(content.starts_with("---\nagentic:\n"));
            assert!(content.contains("once per completed top-level task"));
            assert!(content.contains("Do not retry automatically"));
            assert_eq!(app.managed_records.len(), 1);
            assert_eq!(app.managed_records[0].source, "REVIEW_PIPELINE.md");
        }
    }

    #[test]
    fn review_protocol_dry_run_does_not_write() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.dry_run = true;
        copy_review_pipeline(&mut app, tmp.path()).unwrap();
        assert!(!tmp.path().join("REVIEW_PIPELINE.md").exists());
        assert!(app.managed_records.is_empty());
    }

    #[test]
    fn missing_review_protocol_is_reported() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.kb = crate::kb::Kb::Checkout(tmp.path().to_path_buf());
        let error = copy_review_pipeline(&mut app, tmp.path()).unwrap_err();
        assert!(error.to_string().contains("REVIEW_PIPELINE.md not found"));
    }

    #[test]
    fn unknown_spec_yields_placeholder() {
        let tmp = tempfile::tempdir().unwrap();
        let mut app = test_app(tmp.path());
        app.selected_specs = vec!["software.backend".into(), "software.ghost".into()];
        generate_agents_md(&mut app, tmp.path()).unwrap();
        let content = std::fs::read_to_string(tmp.path().join("AGENTS.md")).unwrap();
        assert!(content.contains("No specialization AGENTS.md template found for software.ghost."));
    }
}
